// Writes src/timezones_gen.rs: every time zone name Node's Intl (ICU) accepts among the IANA tzdb names (with their
// backward links) and ICU's legacy IDs, keyed by its lowercase spelling, with the canonical IANA name Intl resolves it
// to, so the Rust server accepts time zone names exactly as Intl.DateTimeFormat does.
// Usage: node crates/server/tools/gen-timezones.mjs > crates/server/src/timezones_gen.rs
// Candidates: the IANA names listed in go/server/timezones_gen.go (Go's tzdata) plus ICU's legacy identifiers.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const go = readFileSync(`${root}go/server/timezones_gen.go`, 'utf8');
const candidates = new Set([...go.matchAll(/:\s*"([^"]+)",/g)].map((match) => match[1]));
for (const name of Intl.supportedValuesOf('timeZone')) candidates.add(name);
const legacy = [
  'ACT', 'AET', 'AGT', 'ART', 'AST', 'BET', 'BST', 'CAT', 'CNT', 'CST', 'CTT', 'EAT', 'ECT', 'IET', 'IST', 'JST',
  'MIT', 'NET', 'NST', 'PLT', 'PNT', 'PRT', 'PST', 'SST', 'VST', 'EST', 'MST', 'HST', 'UTC', 'GMT', 'UCT', 'UT',
  'Universal', 'Zulu', 'Greenwich', 'GMT0', 'GMT+0', 'GMT-0', 'Etc/GMT0', 'Etc/GMT+0', 'Etc/GMT-0',
  'SystemV/AST4', 'SystemV/AST4ADT', 'SystemV/CST6', 'SystemV/CST6CDT', 'SystemV/EST5', 'SystemV/EST5EDT',
  'SystemV/HST10', 'SystemV/MST7', 'SystemV/MST7MDT', 'SystemV/PST8', 'SystemV/PST8PDT', 'SystemV/YST9',
  'SystemV/YST9YDT',
];
for (const name of legacy) candidates.add(name);
const accepted = new Map();
for (const name of [...candidates].sort()) {
  try {
    const canonical = new Intl.DateTimeFormat('en-US', { timeZone: name }).resolvedOptions().timeZone;
    accepted.set(name.toLowerCase(), canonical);
  } catch {}
}
const lines = [...accepted]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([lower, canonical]) => `    (${JSON.stringify(lower)}, ${JSON.stringify(canonical)}),`);
process.stdout.write(`// Code generated by tools/gen-timezones.mjs (Node ${process.version}, ICU ${process.versions.icu}); DO NOT EDIT.

/// Every time zone name Intl.DateTimeFormat accepts (lowercase, sorted) with the canonical IANA name it resolves to.
#[rustfmt::skip]
pub(crate) const TIME_ZONE_NAMES: &[(&str, &str)] = &[
${lines.join('\n')}
];
`);
