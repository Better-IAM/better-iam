//! Typed request, response and model types of the Better IAM HTTP API, generated from the OpenAPI document the
//! TypeScript implementation publishes (`spec/api/openapi.json`) and its route table (`spec/api/routes.json`), shared
//! by the Rust server and the Rust client.
//!
//! - [`schemas`]: one item per component schema (`Tenant`, `Role`, `AccessPath`, ...), also re-exported at the crate
//!   root. Types better-iam-core already declares (`Tenant`, `Identity`, `AuditEvent`, `Decision`, ...) are
//!   re-exported from it rather than duplicated.
//! - [`api`]: one module per API group with `<Method>Input` (the request body), `<Method>Output` (the `data` of the
//!   answer) and a marker type per route implementing [`routes::Operation`].
//! - [`routes`]: the route table ([`routes::ROUTES`], [`routes::lookup`], [`routes::visit`]).
//! - [`runtime`]: serialization helpers; [`runtime::to_json_string`] writes the JSON text the TypeScript server
//!   writes for the same value.
//!
//! Serialization follows the TypeScript JSON exactly: member names are the TypeScript names, absent optional
//! members stay absent, `null` stays `null`, and members of any type keep any JSON value. Numbers are `f64`
//! (JavaScript numbers).
//!
//! Everything except `lib.rs`, `macros.rs` and `runtime.rs` is generated by `scripts/spec/gen-rust-types.mjs`;
//! `node scripts/spec/check-generated.mjs` fails when the checked-in files are stale.
