// Command gen writes go/client/client_gen.go: one group type per API group of spec/api/routes.json, with one method
// per route, from the typed operation descriptors of go/apitypes/operations_gen.go. Run it from go/client with
//
//	go generate
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
)

// The auth methods and the other routes whose only server parameter is the credential (packages/client
// noInputAuthMethods and noInputMethods): their client methods take no input and send {}.
var noInputAuthMethods = map[string]bool{
	"signOut": true, "getSession": true, "listSessions": true, "revokeOtherSessions": true,
	"beginPasskeyRegistration": true, "listPasskeys": true, "regenerateRecoveryCodes": true, "disableMfa": true,
	"listTrustedDevices": true, "revokeTrustedDevices": true, "mfaStatus": true,
}

var noInputMethods = map[string]bool{"sts/getCallerIdentity": true, "links/list": true, "clearances/templates": true}

var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs", "uri": "URI", "uris": "URIs", "ip": "IP", "ips": "IPs",
	"api": "API", "http": "HTTP", "https": "HTTPS", "json": "JSON",
}

var (
	nonAlnum   = regexp.MustCompile(`[^A-Za-z0-9]+`)
	lowerUpper = regexp.MustCompile(`([a-z0-9])([A-Z])`)
	acronym    = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	commentRe  = regexp.MustCompile(`^\t// Op(\w+) is POST \{basePath\}/(\S+?)\.(?: (.*))?$`)
	declRe     = regexp.MustCompile(`^\tOp(\w+) = Op\[(\w+), (\w+)\]\{&operationTable\[\d+\]\}$`)
)

// pascal is the naming of scripts/spec/gen-go-types.mjs.
func pascal(text string) string {
	spaced := nonAlnum.ReplaceAllString(text, " ")
	spaced = lowerUpper.ReplaceAllString(spaced, "$1 $2")
	spaced = acronym.ReplaceAllString(spaced, "$1 $2")
	var out strings.Builder
	for _, word := range strings.Fields(spaced) {
		if initialism, ok := initialisms[strings.ToLower(word)]; ok {
			out.WriteString(initialism)
			continue
		}
		if len(word) > 1 && word == strings.ToUpper(word) && strings.ContainsAny(word, "ABCDEFGHIJKLMNOPQRSTUVWXYZ") {
			out.WriteString(word[:1] + strings.ToLower(word[1:]))
			continue
		}
		out.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return out.String()
}

type route struct {
	path, group, method string
	op, input, output   string
	summary             string
}

func main() {
	source, err := os.ReadFile("../apitypes/operations_gen.go")
	if err != nil {
		fail(err)
	}
	formatted, err := generate(source)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("client_gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

// generate renders client_gen.go from the source of go/apitypes/operations_gen.go.
func generate(source []byte) ([]byte, error) {
	var routes []route
	var pending *route
	scanner := bufio.NewScanner(bytes.NewReader(source))
	scanner.Buffer(make([]byte, 1<<20), 1<<20)
	for scanner.Scan() {
		line := strings.TrimRight(scanner.Text(), "\r")
		if match := commentRe.FindStringSubmatch(line); match != nil {
			pending = &route{op: "Op" + match[1], path: match[2], summary: strings.TrimSpace(match[3])}
			continue
		}
		if match := declRe.FindStringSubmatch(line); match != nil {
			if pending == nil || pending.op != "Op"+match[1] {
				return nil, fmt.Errorf("descriptor Op%s has no comment", match[1])
			}
			pending.input, pending.output = match[2], match[3]
			routes = append(routes, *pending)
			pending = nil
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	byGroup := map[string][]route{}
	var groupNames []string
	for _, r := range routes {
		parts := strings.Split(r.path, "/")
		if len(parts) != 2 {
			continue // authorize, authorizeMany and listAccessible are Client methods.
		}
		r.group, r.method = parts[0], parts[1]
		if _, ok := byGroup[r.group]; !ok {
			groupNames = append(groupNames, r.group)
		}
		byGroup[r.group] = append(byGroup[r.group], r)
	}
	sort.Strings(groupNames)
	if len(routes) == 0 {
		return nil, fmt.Errorf("no operation descriptors found")
	}

	var b strings.Builder
	b.WriteString("// Code generated by go/client/internal/gen from go/apitypes/operations_gen.go. DO NOT EDIT.\n\n")
	b.WriteString("package client\n\n")
	b.WriteString("import (\n\t\"context\"\n\n\t\"github.com/Better-IAM/better-iam/go/apitypes\"\n)\n\n")
	b.WriteString("// groups holds one field per API group of spec/api/routes.json; each has one method per route.\n")
	b.WriteString("type groups struct {\n")
	for _, group := range groupNames {
		fmt.Fprintf(&b, "\t// %s is the %s API group (POST {basePath}/%s/{method}).\n", pascal(group), group, group)
		fmt.Fprintf(&b, "\t%s %sGroup\n", pascal(group), pascal(group))
	}
	b.WriteString("}\n\n")
	b.WriteString("func newGroups(c *Client) groups {\n\treturn groups{\n")
	for _, group := range groupNames {
		fmt.Fprintf(&b, "\t\t%s: %sGroup{c},\n", pascal(group), pascal(group))
	}
	b.WriteString("\t}\n}\n")
	for _, group := range groupNames {
		name := pascal(group) + "Group"
		fmt.Fprintf(&b, "\n// %s is the %s API group.\ntype %s struct{ c *Client }\n", name, group, name)
		for _, r := range byGroup[group] {
			method := pascal(r.method)
			doc := fmt.Sprintf("// %s is POST {basePath}/%s (%s.%s).", method, r.path, r.group, r.method)
			if r.summary != "" {
				doc += " " + r.summary
			}
			b.WriteString("\n" + doc + "\n")
			switch {
			case (group == "auth" && noInputAuthMethods[r.method]) || noInputMethods[r.path]:
				fmt.Fprintf(&b, "func (g %s) %s(ctx context.Context, options ...CallOptions) (apitypes.%s, error) {\n", name, method, r.output)
				fmt.Fprintf(&b, "\treturn callNoInput[apitypes.%s](ctx, g.c, %q, options)\n}\n", r.output, r.path)
			case r.path == "auth/beginMfa":
				b.WriteString("//\n// Pass the restricted sign-in challenge during enrollment after sign-in, nil during an authenticated session.\n")
				fmt.Fprintf(&b, "func (g %s) %s(ctx context.Context, challenge *MfaChallenge, options ...CallOptions) (apitypes.%s, error) {\n", name, method, r.output)
				b.WriteString("\tif challenge == nil {\n")
				fmt.Fprintf(&b, "\t\treturn callNoInput[apitypes.%s](ctx, g.c, %q, options)\n\t}\n", r.output, r.path)
				fmt.Fprintf(&b, "\treturn Call[apitypes.%s](ctx, g.c, %q, challenge, options...)\n}\n", r.output, r.path)
			case r.path == "auth/confirmMfa":
				fmt.Fprintf(&b, "func (g %s) %s(ctx context.Context, input ConfirmMfaInput, options ...CallOptions) (apitypes.%s, error) {\n", name, method, r.output)
				fmt.Fprintf(&b, "\treturn Call[apitypes.%s](ctx, g.c, %q, input, options...)\n}\n", r.output, r.path)
			default:
				fmt.Fprintf(&b, "func (g %s) %s(ctx context.Context, input apitypes.%s, options ...CallOptions) (apitypes.%s, error) {\n", name, method, r.input, r.output)
				fmt.Fprintf(&b, "\treturn Do(ctx, g.c, apitypes.%s, input, options...)\n}\n", r.op)
			}
		}
	}
	return format.Source([]byte(b.String()))
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
