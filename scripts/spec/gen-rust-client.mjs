#!/usr/bin/env node
// Generates crates/client/src/api.rs, the per-group methods of the Rust client (better-iam-client), from the route
// markers of the generated types crate (crates/types/src/api/*.rs), so every route of spec/api/routes.json is one
// typed method: `client.tenants().create(input)`, `client.auth().get_session()`, `client.authorize(input)`.
//
//   node scripts/spec/gen-rust-client.mjs              write crates/client/src/api.rs
//   node scripts/spec/gen-rust-client.mjs --out DIR    write DIR/src/api.rs instead
//   (--types DIR overrides the crates/types/src/api directory that is read)
//
// Calling conventions follow the TypeScript client (`ClientApi`): authenticated routes take the request body without
// the credential, public routes take their body, the credential-only routes take nothing (their body is `{}`),
// `auth.beginMfa` takes an optional sign-in challenge and `auth.confirmMfa` the client's `ConfirmMfaInput`. The
// special routes (`authorize`, `authorizeMany`, `listAccessible`) are methods of the client itself.
//
// The output is passed through rustfmt; scripts/spec/check-generated.mjs regenerates it into a temporary directory
// and fails when the checked-in file differs.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const option = (name, fallback) => {
  const index = args.indexOf(name);
  return index >= 0 && args[index + 1] ? resolve(args[index + 1]) : fallback;
};
const outDir = option('--out', join(root, 'crates', 'client'));
const typesDir = option('--types', join(root, 'crates', 'types', 'src', 'api'));

const GENERATOR = 'scripts/spec/gen-rust-client.mjs';
const HEADER = `// @generated by ${GENERATOR} from the route markers of crates/types/src/api. Do not edit.`;

const NO_INPUT_AUTH = new Set([
  'signOut',
  'getSession',
  'listSessions',
  'revokeOtherSessions',
  'beginPasskeyRegistration',
  'listPasskeys',
  'regenerateRecoveryCodes',
  'disableMfa',
  'listTrustedDevices',
  'revokeTrustedDevices',
  'mfaStatus',
]);
const NO_INPUT = new Set(['sts/getCallerIdentity', 'links/list', 'clearances/templates']);

const STRICT_KEYWORDS = new Set(
  (
    'as break const continue crate else enum extern false fn for if impl in let loop match mod move mut pub ref ' +
    'return self Self static struct super trait true type unsafe use where while async await dyn abstract become ' +
    'box do final macro override priv typeof unsized virtual yield try gen'
  ).split(' '),
);

function words(text) {
  return String(text)
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .replace(/([A-Za-z])([0-9])/g, '$1 $2')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}
const snake = (text) =>
  words(text)
    .map((word) => word.toLowerCase())
    .join('_');
const ident = (name) => (STRICT_KEYWORDS.has(name) ? `r#${name}` : name);
const pascal = (text) =>
  words(text)
    .map((word) => word[0].toUpperCase() + word.slice(1).toLowerCase())
    .join('');

const MARKER =
  /((?:\/\/\/[^\n]*\n)*)#\[derive\([^\n]*\)\]\npub struct (\w+);\n\nimpl crate::routes::Operation for \2 \{\n\s*type Input = ([^;]+);\n\s*type Output = ([^;]+);\n\s*const ROUTE: crate::routes::Route = crate::routes::Route \{\n\s*path: "([^"]+)",\n\s*group: "([^"]+)",\n\s*method: "([^"]+)",\n\s*public: (true|false),\n\s*call: crate::routes::Call::(\w+),/g;

/** The first paragraph of a marker's doc comment. */
function summary(doc) {
  const lines = doc.split('\n').map((line) => line.replace(/^\/\/\/ ?/, ''));
  const out = [];
  for (const line of lines) {
    if (!line.trim()) break;
    out.push(line);
  }
  return out;
}

/** The markers name their input and output types of the same module. */
const qualify = (module, type) => `better_iam_types::api::${module}::${type}`;

const modules = readdirSync(typesDir)
  .filter((file) => file.endsWith('.rs') && file !== 'mod.rs')
  .map((file) => file.slice(0, -3))
  .sort();

const groups = new Map();
for (const module of modules) {
  const source = readFileSync(join(typesDir, `${module}.rs`), 'utf8').replace(/\r\n/g, '\n');
  for (const match of source.matchAll(MARKER)) {
    const [, doc, marker, input, output, path, group, method, , call] = match;
    const routes = groups.get(module) ?? { group, routes: [] };
    routes.routes.push({
      doc: summary(doc),
      marker,
      input: qualify(module, input.trim()),
      output: qualify(module, output.trim()),
      path,
      group,
      method,
      call,
    });
    groups.set(module, routes);
  }
}
if (!groups.size) throw new Error(`no route markers found in ${typesDir}`);

const docLines = (lines, indent) => lines.map((line) => `${indent}/// ${line}`.trimEnd()).join('\n');

function method(module, route, receiver) {
  const name = ident(snake(route.method));
  const marker = `better_iam_types::api::${module}::${route.marker}`;
  const lines = [...route.doc, '', `\`POST {basePath}/${route.path}\`.`];
  const docs = docLines(lines, '    ');
  if ((route.group === 'auth' && NO_INPUT_AUTH.has(route.method)) || NO_INPUT.has(route.path))
    return `${docs}
    pub fn ${name}(&self) -> crate::Call<${route.output}> {
        ${receiver}.call(${marker}, Default::default())
    }`;
  if (route.path === 'auth/beginMfa')
    return `${docs}
    ///
    /// Pass the sign-in challenge to enrol during sign-in; \`None\` enrols the session's own identity.
    pub fn ${name}(&self, challenge: Option<crate::MfaChallenge>) -> crate::Call<${route.output}> {
        ${receiver}.request(${JSON.stringify(route.path)}, &challenge)
    }`;
  if (route.path === 'auth/confirmMfa')
    return `${docs}
    pub fn ${name}(&self, input: crate::ConfirmMfaInput) -> crate::Call<${route.output}> {
        ${receiver}.request(${JSON.stringify(route.path)}, &input)
    }`;
  return `${docs}
    pub fn ${name}(&self, input: ${route.input}) -> crate::Call<${route.output}> {
        ${receiver}.call(${marker}, input)
    }`;
}

const parts = [
  HEADER,
  `//! The typed methods of every route: one accessor per API group on [\`IamClient\`](crate::IamClient), one method per
//! route, with the request and result types of \`better-iam-types\`.
#![allow(clippy::too_many_lines, clippy::doc_lazy_continuation, clippy::doc_overindented_list_items, clippy::too_long_first_doc_paragraph)]

use crate::IamClient;`,
];

const special = groups.get('operations');
const accessors = [];
const structs = [];
for (const [module, { group, routes }] of groups) {
  if (module === 'operations') continue;
  const type = `${pascal(group)}Api`;
  accessors.push(`    /// The \`${group}\` API group.
    pub fn ${ident(module)}(&self) -> ${type}<'_> {
        ${type} { client: self }
    }`);
  structs.push(`/// The \`${group}\` API group of [\`IamClient\`].
#[derive(Clone, Copy, Debug)]
pub struct ${type}<'a> {
    client: &'a IamClient,
}

impl ${type}<'_> {
${routes.map((route) => method(module, route, 'self.client')).join('\n\n')}
}`);
}
parts.push(`impl IamClient {
${[
  ...(special?.routes ?? []).map((route) => method('operations', route, 'self')),
  ...accessors,
].join('\n\n')}
}`);
parts.push(...structs);

const target = join(outDir, 'src', 'api.rs');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${parts.join('\n\n')}\n`);

function findRustfmt() {
  const exe = process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt';
  const candidates = [];
  if (process.env.RUSTFMT) candidates.push(process.env.RUSTFMT);
  candidates.push('rustfmt');
  const cargoHome = process.env.CARGO_HOME || join(homedir(), '.cargo');
  candidates.push(join(cargoHome, 'bin', exe));
  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ['--version'], { encoding: 'utf8' });
    if (probe.status === 0) return candidate;
  }
  throw new Error(
    'rustfmt was not found (PATH, $RUSTFMT or ~/.cargo/bin); install it with `rustup component add rustfmt`',
  );
}
const result = spawnSync(findRustfmt(), ['--edition', '2024', target], { encoding: 'utf8' });
if (result.status !== 0) {
  process.stderr.write(result.stderr || result.stdout || '');
  throw new Error('rustfmt failed on the generated file');
}
const text = readFileSync(target, 'utf8');
if (text.includes('\r\n')) writeFileSync(target, text.replace(/\r\n/g, '\n'));
const count = [...groups.values()].reduce((sum, { routes }) => sum + routes.length, 0);
console.log(`wrote ${target} (${count} routes in ${groups.size} modules)`);
