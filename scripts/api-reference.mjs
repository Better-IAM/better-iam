// Generates docs/api-reference.md from a live server instance: every API group, its methods, the HTTP route,
// and whether a credential is required. Run after `pnpm build`.
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import {
  betterIam,
  authenticatedAuthMethods,
  publicApiMethods,
  publicAuthMethods,
  routeGroups,
} from '../packages/server/dist/index.js';
import { sqliteAdapter } from '../packages/adapter-sqlite/dist/index.js';

const database = sqliteAdapter({ filename: ':memory:' });
const iam = betterIam({
  database,
  secret: 'api-reference-generator-secret-32-characters',
  baseURL: 'http://localhost:3000',
  authentication: { sendEmail: async () => {}, sendSms: async () => {}, passwordlessEmail: true },
});
const lines = [
  '# API reference',
  '',
  'Generated by `node scripts/api-reference.mjs` from a live `betterIam()` instance. Every method is called as `iam.api.{group}.{method}(credential, input)` on the server and as `client.{group}.{method}(input)` from the typed browser client, which posts `POST {basePath}/{group}/{method}` with a JSON body. Input and result types come from the TypeScript declarations; see the guides for behaviour and permissions.',
  '',
  '## Top-level',
  '',
  '| Method | HTTP | Credential |',
  '| --- | --- | --- |',
  '| `iam.authorize` | `POST /authorize` | required |',
  '| `iam.authorizeMany` | `POST /authorizeMany` | required |',
  '| `iam.listAccessible` | `POST /listAccessible` | required |',
  '| `iam.callPlugin` | `POST /plugins/{pluginId}/{path}` | required |',
  '| health check | `GET /health` | none |',
  '| Prometheus metrics (`observability.metrics.bearerToken`) | `GET /metrics` | metrics bearer token |',
  '| session-token JWKS (`sts.jwt`) | `GET /.well-known/jwks.json` | none |',
  '',
  'Deployment operations without HTTP routes: `initialize`, `bootstrap`, `recoverRoot`, `purgeDeleted`, `pruneAudit`, `archiveAudit`, `sweepExpired`, `selfCheck`, `rotateSecrets`, `assertionKey`, `assertionKeys`, `sessionTokens.jwks`, `sessionTokens.verify`, `features.evaluate`, `features.values`, `features.isEnabled`, `events.subscribe`, `events.dispatch`, `auth.dispatchOutbox`, `protocolHost`, `useProtocol`, `store`.',
  '',
];
let total = 0;
for (const group of Object.keys(iam.api).sort()) {
  const methods = Object.keys(iam.api[group]).sort();
  total += methods.length;
  const routed = group === 'auth' || routeGroups.has(group);
  lines.push(`## ${group}`, '', '| Method | HTTP | Credential |', '| --- | --- | --- |');
  for (const method of methods) {
    const route = routed ? `\`POST /${group}/${method}\`` : 'not routed';
    let credential = 'required';
    if (group === 'auth')
      credential = publicAuthMethods.has(method)
        ? 'none'
        : authenticatedAuthMethods.has(method)
          ? 'required'
          : 'not routed';
    else if (publicApiMethods.has(`${group}/${method}`)) credential = 'none';
    lines.push(`| \`${method}\` | ${route} | ${credential} |`);
  }
  lines.push('');
}
lines.push(`${Object.keys(iam.api).length} groups, ${total} methods.`, '');
await writeFile(resolve(import.meta.dirname, '..', 'docs', 'api-reference.md'), lines.join('\n'));
await database.close();
console.log(`docs/api-reference.md: ${Object.keys(iam.api).length} groups, ${total} methods`);
